"""
幂等性守卫 — 防止数据覆盖写入 (Idempotency Guard)。

模块职责:
    提供轻量级的幂等性检查原语，用于分布式/离线场景下的
    "最后写入胜出"（LWW, Last-Write-Wins）冲突解决。

核心原理:
    基于客户端与服务端各自记录的 `updated_at` 时间戳进行比较：
    - 客户端时间戳 >= 服务端时间戳 → 客户端数据更新或持平，允许写入。
    - 客户端时间戳 <  服务端时间戳 → 客户端数据过时，拒绝写入（服务端已有更新版本）。
    这本质是一个 **向量时钟的退化版本**（仅保留时间维度，不跟踪因果历史）。

设计权衡:
    - 优点: 实现极简、无外部依赖、零额外存储、查询开销 O(1)。
    - 局限: 依赖时钟同步；不同设备间的时钟漂移可能导致"后发先至"被误拒。
      对于 SRS 应用场景（用户答题进度合并），毫秒级精度足够，且用户
      通常不会在多设备间秒级切换，因此 LWW 是可接受的选择。

典型使用场景:
    SRS 离线同步：用户离线做题后回连，需要合并本地与服务端
    的进度。通过比较时间戳，避免用过时的本地数据覆盖服务端
    已被其他设备更新的记录。

扩展方向:
    如需更强的冲突检测（如检测并发修改而非简单覆盖），可升级为
    版本向量（Version Vector）或 CRDT。本模块预留接口签名为
    (client_ts, server_ts) -> bool，升级时只需替换内部实现。

模块版本: 1.0
"""


def check_idempotency(client_updated_at: int, server_updated_at: int) -> bool:
    """
    判断客户端操作是否可以执行（客户端数据不旧于服务端）。

    采用 Last-Write-Wins (LWW) 策略：
    - 若 client_updated_at >= server_updated_at → 允许写入
    - 若 client_updated_at < server_updated_at → 拒绝写入（数据过时）

    本函数是幂等性守卫的核心原语。设计为"纯函数"（无副作用），
    调用方获取布尔返回值后自行决定：
    - True  → 执行 DB 写入 / 状态更新，并可同步更新服务端时间戳。
    - False → 返回 409 Conflict 或静默跳过，保留服务端现有数据。

    Args:
        client_updated_at: 客户端记录的更新时间戳（毫秒级 Unix 时间）。
                           通常来源于离线操作时的 `Date.now()` 或其等效值。
                           类型为 int，不支持浮点秒级时间戳（调用前需自行转换）。
        server_updated_at: 服务端记录的更新时间戳（毫秒级 Unix 时间）。
                           通常从数据库记录的 `updated_at` 字段读取。
                           类型为 int，若记录不存在可传入 0（表示服务端无旧数据）。

    Returns:
        bool: True 表示客户端数据较新或相同，可以安全写入；
              False 表示客户端数据过时，应跳过此操作。

    Raises:
        本函数不主动抛出任何异常。但传入非 int 类型参数时，
        Python 的比较运算符会抛出 TypeError（由调用方保证类型正确）。

    Note:
        - 此函数不做任何副作用（不抛异常、不写日志），
          调用方负责根据返回值决定后续处理逻辑。
        - 时间戳相等（==）被视为"可以写入"，这避免了因精度截断
          导致的伪冲突（例如同一毫秒内连续两次相同写入）。
        - 若服务端无旧记录（server_updated_at == 0），任意
          client_updated_at >= 0 均可通过检查，即首次写入总是允许。

    Example:
        >>> check_idempotency(1700000001000, 1700000000000)
        True   # 客户端时间戳更新，允许写入
        >>> check_idempotency(1700000000000, 1700000001000)
        False  # 客户端时间戳更旧，拒绝写入（数据过时）
        >>> check_idempotency(1700000000000, 1700000000000)
        True   # 时间戳相同，允许写入（幂等放行）
        >>> check_idempotency(1700000000000, 0)
        True   # 服务端无记录，首次写入总是允许
    """
    # LWW 核心判断：客户端时间戳 >= 服务端时间戳 → 允许写入
    # 使用 >= 而非 > 确保相同时间戳的幂等重试不会被拒绝
    return client_updated_at >= server_updated_at
