/// @file 何切题目模型 (Puzzle Model)
///
/// TileZhan 核心数据结构之一，描述一道"何切"(Nani-Kiru / ナニキル)题目。
///
/// ## 何切是什么
/// 何切是日本麻将术语，指玩家手中有 14 张牌（13 张手牌 + 1 张自摸牌），
/// 必须从中舍弃一张以达成最优牌效的问题。这是麻将竞技中最基础也最重要的判断力训练。
///
/// ## 题目结构
/// 一道何切题目由以下要素构成：
/// - 13 张手牌 (hand13Ids)：玩家手牌，不含自摸牌
/// - 1 张自摸牌 (drawnTileId)：当巡摸到的牌，与手牌合为 14 张待切牌面
/// - 1 张正确舍牌 (correctDiscardId)：专家验证的最优解，即最应该舍弃的那张牌
/// - 接受度信息 (ukeire)：正确舍牌后的进张统计，含进张数量、种类及具体牌列表
/// - 难度评级 (difficulty)：Puzzle Rating 评分，范围 800-1300
///
/// ## 数据来源
/// 题目数据通常来自：
/// 1. 职业雀士实战牌谱的人工标注
/// 2. 麻将 AI（如 NAGA/Mortal）的牌效分析结果
/// 3. 经典何切教材（如《何切る300選》）的数字化
///
/// ## 与牌 ID 系统的关系
/// 牌 ID 字符串格式遵循 TileZhan 统一约定：
/// - 数字(1-9) + 花色(m/p/s) 表示数牌，如 "1m" = 一萬, "9p" = 九筒, "5s" = 五索
/// - 数字(1-7) + "z" 表示字牌，如 "1z" = 東, "2z" = 南, "5z" = 白
/// - "0m"/"0p"/"0s" 表示赤宝牌（赤ドラ），仅在特定规则下出现
///
/// ## 与 PuzzleAttempt / PuzzleStats 的关系
/// - 用户作答时创建 [PuzzleAttempt] 记录一次尝试
/// - 多道题目的统计数据汇总为 [PuzzleStats]
///
/// ## 序列化
/// 本模型通过 JSON 序列化与后端 API 交互，字段名使用 camelCase。

/// 何切题目实体类。
///
/// 描述一道完整的何切题目，是 TileZhan 学习系统的核心数据载体。
///
/// ## 字段概览
/// | 字段              | 类型            | 必填 | 说明                         |
/// |-------------------|-----------------|------|------------------------------|
/// | puzzleId          | String          | 是   | 题目唯一标识符               |
/// | hand13Ids         | List\<String\>   | 是   | 13 张手牌 ID 列表            |
/// | drawnTileId       | String          | 是   | 自摸牌 ID                    |
/// | correctDiscardId  | String          | 是   | 正确舍牌 ID（最优解）         |
/// | ukeireCount       | int             | 是   | 正确舍牌后总进张数（张数）    |
/// | ukeireTypes       | int             | 是   | 正确舍牌后进张种类数（种类）  |
/// | ukeireTileIds     | List\<String\>   | 是   | 所有有效进张的牌 ID 列表     |
/// | difficulty        | int             | 否   | Puzzle Rating 难度，默认 1000 |
///
/// ## 使用示例
/// ```dart
/// final puzzle = Puzzle(
///   puzzleId: 'p001',
///   hand13Ids: ['1m','1m','2m','3m','...'],
///   drawnTileId: '4m',
///   correctDiscardId: '1m',
///   ukeireCount: 32,
///   ukeireTypes: 12,
///   ukeireTileIds: ['2m','3m','...'],
///   difficulty: 850,
/// );
/// ```
///
/// ## 不变式 (Invariants)
/// - hand13Ids 固定为 13 张，长度受 PuzzleValidator 校验
/// - drawnTileId 不存在于 hand13Ids 中（自摸牌独立于手牌）
/// - correctDiscardId 必须是 hand13Ids 或 drawnTileId 之一
/// - ukeireCount >= ukeireTypes（因为同一进张种类可能有多张）
/// - ukeireTileIds 的种类数 == ukeireTypes
/// - difficulty 范围 [800, 1300]
///
/// ## 不可变性
/// 本类所有字段均为 final，通过 const 构造函数创建后不可修改。
/// 需要更新字段时，应创建新的 Puzzle 实例（如 Puzzle.copyWith）。
///
/// ## 与后端通信
/// 通过 JSON 序列化/反序列化与 `/api/puzzles` 系列端点交互：
/// - GET    `/api/puzzles/{id}`      → 获取单道题目
/// - GET    `/api/puzzles?page=N`    → 分页获取题目列表
/// - GET    `/api/puzzles/daily`     → 获取今日推荐题目
class Puzzle {
  /// 题目唯一标识符。
  ///
  /// ## 格式
  /// 通常采用 `"p" + 零填充数字` 的格式，如 "p001", "p042", "p123"。
  /// 此格式为约定而非强制约束，后端可能使用 UUID 等其他格式。
  ///
  /// ## 用途
  /// - 与后端 API 交互时作为资源标识符
  /// - 用户提交答案时指定要作答的题目
  /// - 题目书签 / 收藏夹中的引用键
  /// - 统计系统中的外键
  ///
  /// ## 约束
  /// - 全局唯一，不允许重复
  /// - 不可为空字符串
  final String puzzleId;

  /// 手牌 13 张，每张为牌 ID 字符串。
  ///
  /// ## 牌 ID 格式
  /// 遵循 TileZhan 统一牌 ID 约定：
  /// - 数牌：`"{数字1-9}{花色m/p/s}"`，如 `"1m"` = 一萬, `"5p"` = 五筒, `"9s"` = 九索
  /// - 字牌：`"{数字1-7}z"`，如 `"1z"` = 東, `"2z"` = 南, `"3z"` = 西, `"4z"` = 北, `"5z"` = 白, `"6z"` = 發, `"7z"` = 中
  /// - 赤宝牌：`"0m"`, `"0p"`, `"0s"`（仅在含赤规则下出现）
  ///
  /// ## 数据特征
  /// - 固定 13 张，对应日本麻将的标准手牌数
  /// - 列表顺序无严格语义要求，但 UI 展示时通常按花色分组排序
  /// - 允许重复牌 ID（如手中有对子/刻子）
  /// - 与 [drawnTileId] 合起来构成 14 张待切牌面
  ///
  /// ## 显示时的排序约定
  /// 前端渲染时通常按以下顺序排列：
  /// 1. 萬子 (m) 按数字 1-9 升序
  /// 2. 筒子 (p) 按数字 1-9 升序
  /// 3. 索子 (s) 按数字 1-9 升序
  /// 4. 字牌 (z) 按 1-7 升序
  final List<String> hand13Ids;

  /// 自摸牌 ID，摸到手牌后总计 14 张。
  ///
  /// ## 含义
  /// 这张牌是玩家在当前巡目从牌山摸到的牌。它与 13 张手牌合并后构成"何切"的判断基础
  /// —— 玩家需要从这 14 张里选一张舍牌。
  ///
  /// ## UI 展示
  /// 前端通常将自摸牌与手牌分开展示：
  /// - 手牌 13 张横向排列
  /// - 自摸牌单独放置在手牌右侧，稍微间隔以区分"手中原有的"和"刚摸到的"
  /// - 或使用高亮/旋转动效标识自摸牌
  ///
  /// ## 约束
  /// - 牌 ID 格式与 [hand13Ids] 中的元素相同
  /// - 理论上自摸牌可能与手牌中已有的牌相同（如手中有 1m，又摸到 1m），这是完全合法的
  /// - 不可为空字符串
  final String drawnTileId;

  /// 正确舍牌 ID（最优舍牌，经专家验证）。
  ///
  /// ## 来源
  /// 正确舍牌由以下方式之一确定：
  /// 1. **职业雀士标注**：天凤位/雀聖等高段位玩家的实战选择
  /// 2. **AI 分析**：NAGA / Mortal 等麻将 AI 的牌效最优解
  /// 3. **共识解**：经典何切教材中的公认答案
  ///
  /// ## 语义
  /// 在 14 张牌（13 手牌 + 1 自摸牌）中，舍弃此牌后：
  /// - 向听数（shanten）最优（即离听牌最近）
  /// - 在等向听情况下，进张数（ukeire）最大
  /// - 兼顾打点、安全性等综合因素的全局最优解
  ///
  /// ## 约束
  /// - 必须是 [hand13Ids] 或 [drawnTileId] 中的一张
  /// - 如果 hand13Ids 中有多张相同牌，correctDiscardId 只需指定其中一张
  ///   （因为舍哪张同名牌在牌效上等价）
  /// - 不可为空字符串
  final String correctDiscardId;

  /// 正确舍牌后的总进张数（张数维度）。
  ///
  /// ## 定义
  /// 进张（ukeire / 有効牌）指：舍弃 [correctDiscardId] 后，摸到某张牌能使向听数减少的牌。
  /// 本字段统计所有有效进张的**总张数**，即考虑每种牌在牌山中的剩余枚数。
  ///
  /// ## 计算方式
  /// 例如，舍弃某牌后，进张种类为 {2m, 3m, 5p}：
  /// - 2m 剩余 4 张 → 4
  /// - 3m 剩余 3 张 → 3
  /// - 5p 剩余 4 张 → 4
  /// - ukeireCount = 4 + 3 + 4 = 11
  ///
  /// ## 与 ukeireTypes 的关系
  /// - ukeireCount >= ukeireTypes 恒成立
  /// - 若 ukeireCount == ukeireTypes，说明每种进张在牌山中仅剩 1 张（极端坏形）
  /// - ukeireCount 越大，说明摸到有效牌的概率越高，听牌越容易
  ///
  /// ## 使用场景
  /// - 在题目详情页展示进张统计
  /// - 用于计算题目的客观难度（进张少 → 判断更难）
  /// - 用户作答反馈中告知"正确舍牌后有 XX 张进张"
  final int ukeireCount;

  /// 正确舍牌后的进张种类数（种类维度）。
  ///
  /// ## 定义
  /// 进张种类数 = 有多少种**不同的牌**能使向听数减少，不考虑每种牌的剩余枚数。
  ///
  /// ## 示例
  /// 进张为 {2m, 3m, 5p} → ukeireTypes = 3（3 种不同的牌）
  /// 进张为 {1m, 4m, 7m, 1p, 4p} → ukeireTypes = 5
  ///
  /// ## 与 ukeireCount 的关系
  /// - ukeireTypes <= ukeireCount 恒成立
  /// - ukeireTypes 反映"进张面有多宽"（好形/坏形判断）
  /// - ukeireCount 反映"进张量有多大"（实际概率）
  /// - 通常：ukeireTypes 多 = 好形两面听；ukeireTypes 少 = 愚形嵌张/边张听
  ///
  /// ## 战略意义
  /// 在实战中，ukeireTypes 比 ukeireCount 更直观：
  /// - 进张种类 10+ → 超好形，几乎必听
  /// - 进张种类 6-9 → 良形，普通两面/三面听
  /// - 进张种类 3-5 → 愚形，嵌张/边张
  /// - 进张种类 1-2 → 绝愚形，边张单骑
  final int ukeireTypes;

  /// 所有有效进张的牌 ID 列表。
  ///
  /// ## 内容
  /// 列出舍弃 [correctDiscardId] 后所有能使向听数前进的牌。
  /// 列表中可能出现重复（同一种牌有多枚时），取决于后端数据约定。
  /// 通常每种牌只出现一次，余枚信息通过去重后的 [ukeireTypes] 反映。
  ///
  /// ## 用途
  /// - 题目详情页高亮展示所有进张牌
  /// - 用户作答后，高亮用户错过的进张（用户舍牌 vs 正确舍牌的进张对比）
  /// - 牌谱分析功能中，计算某舍牌后的进张分布
  ///
  /// ## UI 渲染
  /// 前端在展示进张时：
  /// 1. 将 ukeireTileIds 中的牌按花色归类
  /// 2. 渲染为迷你牌面列表
  /// 3. 对于用户未选择正确舍牌的情况，展示"你损失了 XX 种进张"
  ///
  /// ## 约束
  /// - 去重后的元素数量应等于 [ukeireTypes]
  /// - 列表中的每个牌 ID 必须来自标准麻将牌集合（34 种牌）
  final List<String> ukeireTileIds;

  /// 题目难度评级（Puzzle Rating），范围 800-1300，默认 1000。
  ///
  /// ## 评级体系
  /// Puzzle Rating 采用类 ELO 的序数评分系统，用于衡量题目的客观难度：
  /// | 评级   | 范围       | 含义                       |
  /// |--------|------------|----------------------------|
  /// | 800    | 入门       | 极简单，新手向，通常为明显的最优舍牌（如舍孤张字牌） |
  /// | 850    | 初级       | 简单，有基本牌效意识的玩家都能答对 |
  /// | 950    | 中级       | 中等，需要基础牌效计算 |
  /// | 1050   | 上级       | 较难，需要考虑复合搭子、多面张 |
  /// | 1150   | 特上       | 非常难，涉及 dora/安全牌/场况等多因素权衡 |
  /// | 1250+  | 雀聖级     | 极难，职业雀士级别判断，涉及全局战略取舍 |
  ///
  /// ## 计算依据
  /// 难度评级综合以下因素：
  /// 1. **进张差异度**：错误舍牌与正确舍牌的 ukeire 差距，差距越小难度越高
  /// 2. **候补舍牌数**：有多少张牌的 ukeire 接近最优解，候补越多迷惑性越大
  /// 3. **向听深度**：当前牌面的向听数，向听越深计算越复杂
  /// 4. **用户正解率**：通过用户作答数据反向校准（贝叶斯估计）
  ///
  /// ## 默认值
  /// 新题目的初始难度为 1000，随后根据用户答题数据动态调整。
  ///
  /// ## 约束
  /// - 范围 [800, 1300]，由 PuzzleValidator 校验
  /// - 数值越高表示题目越难
  final int difficulty;

  /// 创建何切题目。
  ///
  /// ## 参数说明
  /// | 参数               | 类型            | 必填 | 默认值 | 说明                         |
  /// |--------------------|-----------------|------|--------|------------------------------|
  /// | puzzleId           | String          | 是   | -      | 题目唯一标识符               |
  /// | hand13Ids          | List\<String\>   | 是   | -      | 13 张手牌 ID 列表            |
  /// | drawnTileId        | String          | 是   | -      | 自摸牌 ID                    |
  /// | correctDiscardId   | String          | 是   | -      | 正确舍牌 ID                  |
  /// | ukeireCount        | int             | 是   | -      | 总进张数（张数维度）          |
  /// | ukeireTypes        | int             | 是   | -      | 进张种类数（种类维度）        |
  /// | ukeireTileIds      | List\<String\>   | 是   | -      | 所有有效进张牌 ID 列表       |
  /// | difficulty         | int             | 否   | 1000   | Puzzle Rating 难度评级       |
  ///
  /// ## 构造后不变量
  /// 使用 `const` 构造函数，实例在编译期或运行期创建后不可修改。
  /// 如需修改字段，应实现 copyWith 工厂方法返回新实例。
  ///
  /// ## 使用示例
  /// ```dart
  /// final puzzle = Puzzle(
  ///   puzzleId: 'p042',
  ///   hand13Ids: ['1m','1m','3m','4m','5m','7m','8m','9m','1p','2p','3p','5s','6s'],
  ///   drawnTileId: '7s',
  ///   correctDiscardId: '1m',
  ///   ukeireCount: 28,
  ///   ukeireTypes: 10,
  ///   ukeireTileIds: ['2m','3m','...'],
  /// );
  /// ```
  const Puzzle({
    required this.puzzleId,
    required this.hand13Ids,
    required this.drawnTileId,
    required this.correctDiscardId,
    required this.ukeireCount,
    required this.ukeireTypes,
    required this.ukeireTileIds,
    this.difficulty = 1000,
  });
}
